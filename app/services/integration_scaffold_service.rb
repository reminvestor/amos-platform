class IntegrationScaffoldService
  def generate_scaffold(app_name:, slug:, auth_type:, base_url: nil, description: nil, entity:, user:)
    Rails.logger.info "🏗️ Generating integration scaffold for #{app_name}"
    
    begin
      files_created = []
      
      # 1. Create Integration record
      integration = create_integration_record(
        app_name: app_name,
        slug: slug,
        auth_type: auth_type,
        base_url: base_url,
        description: description,
        entity: entity
      )
      
      # 2. Create directory structure
      base_dir = Rails.root.join('app', 'services', 'integrations', slug)
      FileUtils.mkdir_p(base_dir)
      
      # 3. Generate base service file
      service_file = generate_base_service(integration, base_dir)
      files_created << service_file
      
      # 4. Generate auth module
      auth_file = generate_auth_module(integration, base_dir)
      files_created << auth_file
      
      # 5. Generate error handler
      error_file = generate_error_handler(integration, base_dir)
      files_created << error_file
      
      # 6. Generate operations file (empty scaffold)
      operations_file = generate_operations_file(integration, base_dir)
      files_created << operations_file
      
      # 7. Create initial connection for the user
      connection = create_initial_connection(integration, entity, user)
      
      # 8. Run auto-discovery to register operations
      Rails.logger.info "🔍 Running auto-discovery for new integration..."
      OperationDiscoveryService.discover_integration(integration.slug)
      
      {
        success: true,
        integration_id: integration.id,
        connection_id: connection.id,
        files_created: files_created,
        scaffold_path: base_dir.to_s
      }
    rescue => e
      Rails.logger.error "Scaffold generation failed: #{e.message}"
      Rails.logger.error e.backtrace.join("\n")
      { success: false, error: e.message }
    end
  end
  
  private
  
  def create_integration_record(app_name:, slug:, auth_type:, base_url:, description:, entity:)
    Integration.create!(
      name: app_name,
      slug: slug,
      description: description || "Integration with #{app_name}",
      category: 'custom',
      auth_type: auth_type,
      api_base_url: base_url || "https://api.#{slug}.com",
      is_active: true,
      is_custom: true,
      metadata: {
        created_by: 'ai_integration_builder',
        auth_type: auth_type
      }
    )
  end
  
  def generate_base_service(integration, base_dir)
    file_path = base_dir.join("#{integration.slug}_service.rb")
    
    code = <<~RUBY
      # #{integration.name} Integration Service
      # Generated by AI Integration Builder
      
      module Integrations
        module #{integration.slug.camelize}
          class #{integration.slug.camelize}Service < Integrations::BaseService
            def initialize(connection)
              super(connection)
              @auth = #{integration.slug.camelize}Auth.new(connection)
            end
            
            # Universal executor will call this method
            def execute_operation(operation_id, params = {})
              # Try to find and call the method
              method_name = operation_id.to_sym
              
              if respond_to?(method_name, true)
                send(method_name, **params.symbolize_keys)
              else
                { success: false, error: "Operation '\#{operation_id}' not found" }
              end
            end
            
            # List available operations (for discovery)
            def available_operations
              # Get all public methods excluding base class methods
              base_methods = Integrations::BaseService.instance_methods
              (self.class.instance_methods(false) - base_methods).map(&:to_s)
            end
            
            # Override base_url if needed
            def base_url
              '#{integration.api_base_url || "https://api.#{integration.slug}.com"}'
            end
            
            # Override authentication_headers if needed
            # def authentication_headers
            #   # Custom authentication logic
            #   super
            # end
          end
        end
      end
    RUBY
    
    File.write(file_path, code)
    file_path.to_s
  end
  
  def generate_auth_module(integration, base_dir)
    file_path = base_dir.join("#{integration.slug}_auth.rb")
    
    code = case integration.auth_type
    when 'oauth2'
      generate_oauth2_auth(integration)
    when 'api_key'
      generate_api_key_auth(integration)
    when 'bearer_token'
      generate_bearer_token_auth(integration)
    when 'basic_auth'
      generate_basic_auth(integration)
    else
      generate_api_key_auth(integration) # Default
    end
    
    File.write(file_path, code)
    file_path.to_s
  end
  
  def generate_oauth2_auth(integration)
    <<~RUBY
      # OAuth2 Authentication for #{integration.name}
      
      module Integrations
        module #{integration.slug.camelize}
          class #{integration.slug.camelize}Auth
            attr_reader :connection
            
            def initialize(connection)
              @connection = connection
            end
            
            def headers
              {
                'Authorization' => "Bearer \#{access_token}",
                'Content-Type' => 'application/json',
                'Accept' => 'application/json'
              }
            end
            
            def access_token
              # Check if token is expired
              if token_expired?
                refresh_token!
              end
              
              credential = @connection.active_credential
              return nil unless credential
              
              credential.credentials['access_token']
            end
            
            private
            
            def token_expired?
              credential = @connection.active_credential
              return true unless credential
              
              credential.expired? || credential.needs_refresh?
            end
            
            def refresh_token!
              # TODO: Implement OAuth2 token refresh
              # This will be customized based on the specific API
              Rails.logger.warn "OAuth2 token refresh not yet implemented for #{integration.name}"
            end
          end
        end
      end
    RUBY
  end
  
