  def generate_basic_auth(integration)
    <<~RUBY
      # Basic Authentication for #{integration.name}
      
      module Integrations
        module #{integration.slug.camelize}
          class #{integration.slug.camelize}Auth
            attr_reader :connection
            
            def initialize(connection)
              @connection = connection
            end
            
            def headers
              {
                'Authorization' => basic_auth_header,
                'Content-Type' => 'application/json',
                'Accept' => 'application/json'
              }
            end
            
            private
            
            def basic_auth_header
              credential = @connection.active_credential
              return '' unless credential
              
              username = credential.credentials['username']
              password = credential.credentials['password']
              credentials = Base64.strict_encode64("\#{username}:\#{password}")
              "Basic \#{credentials}"
            end
          end
        end
      end
    RUBY
  end
  
  def generate_error_handler(integration, base_dir)
    file_path = base_dir.join("error_handler.rb")
    
    code = <<~RUBY
      # Error Handler for #{integration.name} Integration
      
      module Integrations
        module #{integration.slug.camelize}
          class ErrorHandler
            def self.handle(error)
              case error
              when RestClient::Unauthorized
                {
                  success: false,
                  error: 'Authentication failed',
                  error_type: 'unauthorized',
                  message: 'Invalid or expired credentials',
                  status: 401
                }
              when RestClient::Forbidden
                {
                  success: false,
                  error: 'Access forbidden',
                  error_type: 'forbidden',
                  message: 'You do not have permission to access this resource',
                  status: 403
                }
              when RestClient::NotFound
                {
                  success: false,
                  error: 'Resource not found',
                  error_type: 'not_found',
                  message: 'The requested resource does not exist',
                  status: 404
                }
              when RestClient::TooManyRequests
                {
                  success: false,
                  error: 'Rate limit exceeded',
                  error_type: 'rate_limit',
                  message: 'Too many requests. Please try again later.',
                  status: 429,
                  retry_after: error.response.headers[:retry_after]
                }
              when RestClient::BadRequest
                {
                  success: false,
                  error: 'Bad request',
                  error_type: 'bad_request',
                  message: parse_error_message(error.response),
                  status: 400
                }
              else
                {
                  success: false,
                  error: 'API request failed',
                  error_type: 'unknown',
                  message: error.message,
                  status: error.try(:response)&.code || 500
                }
              end
            end
            
            private
            
            def self.parse_error_message(response)
              JSON.parse(response.body)['message'] rescue response.body
            end
          end
        end
      end
    RUBY
    
    File.write(file_path, code)
    file_path.to_s
  end
  
  def generate_operations_file(integration, base_dir)
    file_path = base_dir.join("operations.rb")
    
    code = <<~RUBY
      # Operations for #{integration.name} Integration
      # Add your API endpoint methods here
      
      module Integrations
        module #{integration.slug.camelize}
          module Operations
            # Example operation:
            # def get_user(user_id)
            #   request(:get, "/users/\#{user_id}")
            # end
            
            # Add your operations below:
            
          end
        end
      end
      
      # Include operations in the main service
      Integrations::#{integration.slug.camelize}::#{integration.slug.camelize}Service.include(
        Integrations::#{integration.slug.camelize}::Operations
      )
    RUBY
    
    File.write(file_path, code)
    file_path.to_s
  end
  
  def create_initial_connection(integration, entity, user)
    connection = Connection.create!(
      integration: integration,
      entity: entity,
      name: "#{integration.name} Connection",
      status: :disconnected,
      metadata: {
        created_by: 'ai_integration_builder',
        setup_required: true
      }
    )
    
    # Create pending credential record
    connection.integration_credentials.create!(
      name: "#{integration.name} Credentials",
      credentials: {}.to_json,
      auth_method: 'header',
      status: :expired,
      metadata: {
        pending_setup: true
      }
    )
    
    connection
  end
end

